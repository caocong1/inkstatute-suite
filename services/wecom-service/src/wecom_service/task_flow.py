"""Backend-neutral WeCom task-flow primitives.

The task flow intentionally separates service-owned progress from model
reasoning. User-visible progress is generated by InkStatute from these stages;
hidden reasoning, Hermes gateway output, paths, commands, tokens, and runtime
details are never forwarded as progress.

Task stages used by the live WeCom runtime:
received, turn_ready, queued, running, progress_notice_due, artifact_ready,
completed, failed, timeout, cancelled.

Platform AsyncTaskState mapping:
queued -> queued; running/progress_notice_due/artifact_ready -> running;
completed -> succeeded; failed/timeout -> failed; cancelled -> cancelled.
received and turn_ready are service-only ExecutionTrace metadata stages.

Adjacent file plus text WeCom events are aggregated into one turn before one
task is created. A second user message while a task is running must go through
the fast active-task control plane, not wait behind the running task.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from datetime import datetime, timedelta, timezone
from enum import StrEnum
from typing import Any, Iterable

from platform_contract import AsyncTaskState
from platform_contract.utils import coerce_datetime, sha256_short


JsonObject = dict[str, Any]


class WeComTaskStage(StrEnum):
    RECEIVED = "received"
    TURN_READY = "turn_ready"
    QUEUED = "queued"
    RUNNING = "running"
    PROGRESS_NOTICE_DUE = "progress_notice_due"
    ARTIFACT_READY = "artifact_ready"
    COMPLETED = "completed"
    FAILED = "failed"
    TIMEOUT = "timeout"
    CANCELLED = "cancelled"


TASK_STAGE_TO_ASYNC_STATE: dict[WeComTaskStage, AsyncTaskState | None] = {
    WeComTaskStage.RECEIVED: None,
    WeComTaskStage.TURN_READY: None,
    WeComTaskStage.QUEUED: AsyncTaskState.QUEUED,
    WeComTaskStage.RUNNING: AsyncTaskState.RUNNING,
    WeComTaskStage.PROGRESS_NOTICE_DUE: AsyncTaskState.RUNNING,
    WeComTaskStage.ARTIFACT_READY: AsyncTaskState.RUNNING,
    WeComTaskStage.COMPLETED: AsyncTaskState.SUCCEEDED,
    WeComTaskStage.FAILED: AsyncTaskState.FAILED,
    WeComTaskStage.TIMEOUT: AsyncTaskState.FAILED,
    WeComTaskStage.CANCELLED: AsyncTaskState.CANCELLED,
}

TERMINAL_TASK_STAGES = {
    WeComTaskStage.COMPLETED,
    WeComTaskStage.FAILED,
    WeComTaskStage.TIMEOUT,
    WeComTaskStage.CANCELLED,
}


@dataclass(frozen=True, slots=True)
class TaskInputSummary:
    text_sha256_16: str
    text_length: int
    media_count: int
    media_types: tuple[str, ...] = ()
    raw_payload_ref: str | None = None

    def as_event_metadata(self) -> JsonObject:
        return {
            "text_sha256_16": self.text_sha256_16,
            "text_length": self.text_length,
            "media_count": self.media_count,
            "media_types": list(self.media_types),
            "raw_payload_ref": self.raw_payload_ref,
            "privacy": "no_raw_payload_or_legal_text_stored",
            "file_text_aggregation": "adjacent_wecom_events_become_one_task",
        }


@dataclass(frozen=True, slots=True)
class TaskFlowConfig:
    progress_interval_seconds: float = 180.0
    timeout_seconds: float = 7200.0


@dataclass(frozen=True, slots=True)
class TaskStageRecord:
    task_id: str
    trace_id: str
    stage: WeComTaskStage
    occurred_at: str
    seq: int
    async_task_state: str | None
    idempotency_key: str
    metadata: JsonObject = field(default_factory=dict)

    def as_event(self) -> JsonObject:
        event = {
            "event": "wecom_task_flow",
            "task_id": self.task_id,
            "trace_id": self.trace_id,
            "stage": self.stage.value,
            "occurred_at": self.occurred_at,
            "seq": self.seq,
            "idempotency_key": self.idempotency_key,
            "metadata": self.metadata,
        }
        if self.async_task_state is not None:
            event["async_task_state"] = self.async_task_state
        return event


@dataclass(slots=True)
class TaskFlow:
    task_id: str
    trace_id: str
    conversation_id: str
    user_id_hash: str
    input_summary: TaskInputSummary
    config: TaskFlowConfig
    created_at: datetime
    deadline_at: datetime
    stage_records: list[TaskStageRecord] = field(default_factory=list)
    current_stage: WeComTaskStage = WeComTaskStage.RECEIVED
    last_progress_notice_at: datetime | None = None

    @property
    def active(self) -> bool:
        return self.current_stage not in TERMINAL_TASK_STAGES

    @property
    def async_task_state(self) -> str | None:
        state = TASK_STAGE_TO_ASYNC_STATE[self.current_stage]
        return state.value if state is not None else None


def summarize_task_input(
    *,
    text: str | None,
    media_types: Iterable[str] = (),
    media_count: int | None = None,
    raw_payload_ref: str | None = None,
) -> TaskInputSummary:
    """Summarize a merged WeCom turn without storing raw user text."""

    text_value = str(text or "")
    media_types_tuple = tuple(str(item or "unknown") for item in media_types)
    return TaskInputSummary(
        text_sha256_16=sha256_short(text_value),
        text_length=len(text_value),
        media_count=len(media_types_tuple) if media_count is None else int(media_count),
        media_types=media_types_tuple,
        raw_payload_ref=raw_payload_ref,
    )


def create_task_flow(
    *,
    conversation_id: str,
    user_id: str,
    message_id: str,
    text: str | None,
    media_types: Iterable[str] = (),
    raw_payload_ref: str | None = None,
    now: datetime | str | None = None,
    config: TaskFlowConfig | None = None,
) -> TaskFlow:
    """Create a task for one already-aggregated WeCom turn."""

    current = coerce_datetime(now)
    cfg = config or TaskFlowConfig()
    input_summary = summarize_task_input(text=text, media_types=media_types, raw_payload_ref=raw_payload_ref)
    identity = ":".join(
        [
            "wecom-task",
            str(conversation_id),
            str(user_id),
            str(message_id),
            input_summary.text_sha256_16,
            str(input_summary.media_count),
        ]
    )
    task_id = f"wecom-task-{sha256_short(identity)}"
    trace_id = f"trace-{sha256_short(task_id + ':trace')}"
    task = TaskFlow(
        task_id=task_id,
        trace_id=trace_id,
        conversation_id=str(conversation_id),
        user_id_hash=sha256_short(str(user_id)),
        input_summary=input_summary,
        config=cfg,
        created_at=current,
        deadline_at=current + timedelta(seconds=max(0.0, cfg.timeout_seconds)),
    )
    record_stage(
        task,
        WeComTaskStage.TURN_READY,
        now=current,
        metadata={
            "service_boundary": "inkstatute_wecom_service",
            "agent_backend_boundary": "adapter_only",
            "wecom_ingress_egress_owner": "inkstatute",
            "progress_owner": "inkstatute_wecom_service",
            "model_reasoning_forwarded": False,
            "active_task_followup_route": "fast_control_plane",
            **input_summary.as_event_metadata(),
        },
    )
    return task


def record_stage(
    task: TaskFlow,
    stage: WeComTaskStage | str,
    *,
    now: datetime | str | None = None,
    metadata: JsonObject | None = None,
) -> TaskStageRecord:
    """Append a minimized task-stage event and update in-memory task state."""

    task_stage = WeComTaskStage(str(stage))
    current = coerce_datetime(now)
    seq = len(task.stage_records) + 1
    async_state = TASK_STAGE_TO_ASYNC_STATE[task_stage]
    stage_metadata: JsonObject = {
        "service_stage": task_stage.value,
        "execution_trace_mapping": "metadata" if async_state is None else "async_task_state",
        "service_owned_progress": task_stage is WeComTaskStage.PROGRESS_NOTICE_DUE,
        "privacy": "no_raw_payload_or_legal_text_stored",
    }
    if metadata:
        stage_metadata.update(metadata)

    record = TaskStageRecord(
        task_id=task.task_id,
        trace_id=task.trace_id,
        stage=task_stage,
        occurred_at=current.isoformat(),
        seq=seq,
        async_task_state=async_state.value if async_state is not None else None,
        idempotency_key=task_stage_idempotency_key(task.task_id, task_stage, seq),
        metadata=stage_metadata,
    )
    task.stage_records.append(record)
    task.current_stage = task_stage
    if task_stage is WeComTaskStage.PROGRESS_NOTICE_DUE:
        task.last_progress_notice_at = current
    return record


def progress_notice_due(task: TaskFlow, *, now: datetime | str | None = None) -> bool:
    """Return true when a service-owned progress notice should be sent."""

    if not task.active or task.current_stage not in {
        WeComTaskStage.RUNNING,
        WeComTaskStage.PROGRESS_NOTICE_DUE,
        WeComTaskStage.ARTIFACT_READY,
    }:
        return False
    interval = max(0.0, task.config.progress_interval_seconds)
    if interval == 0:
        return False
    current = coerce_datetime(now)
    baseline = task.last_progress_notice_at or _last_stage_time(task, WeComTaskStage.RUNNING) or task.created_at
    return current >= baseline + timedelta(seconds=interval)


def deadline_exceeded(task: TaskFlow, *, now: datetime | str | None = None) -> bool:
    return coerce_datetime(now) >= task.deadline_at


def task_stage_idempotency_key(task_id: str, stage: WeComTaskStage | str, seq: int) -> str:
    return f"wecom-task:{task_id}:{str(stage)}:{seq}"


def task_snapshot(task: TaskFlow) -> JsonObject:
    """Return a minimized active-task snapshot for control-plane routing."""

    return {
        "task_id": task.task_id,
        "trace_id": task.trace_id,
        "conversation_id": task.conversation_id,
        "user_id_hash": task.user_id_hash,
        "stage": task.current_stage.value,
        "async_task_state": task.async_task_state,
        "created_at": task.created_at.isoformat(),
        "deadline_at": task.deadline_at.isoformat(),
        "progress_notice_count": sum(
            1 for record in task.stage_records if record.stage is WeComTaskStage.PROGRESS_NOTICE_DUE
        ),
        "privacy": "no_raw_payload_or_legal_text_stored",
    }


def _last_stage_time(task: TaskFlow, stage: WeComTaskStage) -> datetime | None:
    for record in reversed(task.stage_records):
        if record.stage is stage:
            return coerce_datetime(record.occurred_at)
    return None


