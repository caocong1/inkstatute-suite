"""Deterministic TypeScript SDK generator for the platform API OpenAPI document.

The generator is a pure function: it takes the OpenAPI document (as a
mapping) and returns a TypeScript source string. Sorting is applied to all
multi-valued collections so that running the generator twice on the same
input produces byte-identical output.

The generated SDK is intentionally remote/thin. It exposes plain async
methods that return parsed JSON. No local runtime, queue, database, or
backend construction is included.
"""

from __future__ import annotations

import argparse
import json
import os
import sys
from typing import Any, Iterable, Mapping

SDK_HEADER = """\
// Auto-generated by packages/platform-sdk-ts/scripts/generate_sdk.py.
// Do not edit by hand. Regenerate via:
//   python packages/platform-sdk-ts/scripts/generate_sdk.py
//
// This SDK is remote/thin: it makes HTTP requests against a platform API
// host and never embeds a local runtime, queue, or database.

export interface PlatformApiClientOptions {
  baseUrl: string;
  fetchImpl?: typeof fetch;
  defaultHeaders?: Record<string, string>;
}

export interface SseFrame {
  event: string;
  id: string;
  data: string;
}

export class PlatformApiError extends Error {
  readonly status: number;
  readonly code: string;
  readonly details: Record<string, unknown>;

  constructor(
    message: string,
    options: { status: number; code: string; details?: Record<string, unknown> },
  ) {
    super(message);
    this.name = "PlatformApiError";
    this.status = options.status;
    this.code = options.code;
    this.details = options.details ?? {};
  }
}

function parseSseFrame(rawFrame: string): SseFrame | null {
  const lines = rawFrame.split("\\n");
  let event = "message";
  let id = "";
  let data: string[] = [];
  for (const line of lines) {
    if (line.startsWith("event: ")) event = line.slice("event: ".length);
    else if (line.startsWith("id: ")) id = line.slice("id: ".length);
    else if (line.startsWith("data: ")) data.push(line.slice("data: ".length));
  }
  if (!event && data.length === 0) return null;
  return { event, id, data: data.join("\\n") };
}
"""

SDK_CLIENT = """\
export class PlatformApiClient {
  private readonly baseUrl: string;
  private readonly fetchImpl: typeof fetch;
  private readonly defaultHeaders: Record<string, string>;

  constructor(options: PlatformApiClientOptions) {
    this.baseUrl = options.baseUrl.replace(/\\/$/, "");
    this.fetchImpl = options.fetchImpl ?? fetch;
    this.defaultHeaders = options.defaultHeaders ?? {};
  }

{operations}

  private async request<TResponse>(
    method: string,
    path: string,
    body: unknown | undefined,
  ): Promise<TResponse> {
    const response = await this.fetchImpl(this.baseUrl + path, {
      method,
      headers: {
        "content-type": "application/json",
        ...this.defaultHeaders,
      },
      body: body === undefined ? undefined : JSON.stringify(body),
    });
    const text = await response.text();
    const parsed = text.length > 0 ? (JSON.parse(text) as unknown) : null;
    if (!response.ok) {
      const errorBody = (parsed ?? {}) as { code?: string; message?: string; details?: Record<string, unknown> };
      throw new PlatformApiError(errorBody.message ?? response.statusText, {
        status: response.status,
        code: errorBody.code ?? "platform_api_error",
        details: errorBody.details,
      });
    }
    return parsed as TResponse;
  }
}
"""


def generate_typescript(openapi: Mapping[str, Any]) -> str:
    operations = list(_collect_operations(openapi))
    operations.sort(key=lambda op: op["function_name"])
    methods = "\n\n".join(_render_operation(op) for op in operations)
    body = SDK_CLIENT.replace("{operations}", methods)
    return SDK_HEADER + body


def write_typescript(text: str, output_path: str) -> None:
    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    with open(output_path, "w", encoding="utf-8") as fp:
        fp.write(text.rstrip() + "\n")


def _collect_operations(openapi: Mapping[str, Any]) -> Iterable[dict[str, Any]]:
    paths = openapi.get("paths", {}) or {}
    http_methods = {"get", "post", "put", "delete", "patch"}
    for raw_path in sorted(paths.keys()):
        path_item = paths[raw_path] or {}
        for method in sorted(m for m in path_item.keys() if m in http_methods):
            op = path_item[method] or {}
            all_params = list(path_item.get("parameters", []) or []) + list(op.get("parameters", []) or [])
            yield {
                "function_name": _function_name(raw_path, method, op.get("operationId")),
                "summary": op.get("summary", ""),
                "method": method.upper(),
                "path": raw_path,
                "path_params": _path_params(raw_path, all_params),
                "header_params": _header_params(all_params),
                "has_body": method in {"post", "put", "patch"} and "requestBody" in op,
                "stream": "text/event-stream" in (op.get("responses", {}).get("200", {}).get("content", {}) or {}),
            }


def _function_name(path: str, method: str, operation_id: str | None) -> str:
    if operation_id:
        return _to_camel_case(operation_id)
    segments = [seg for seg in path.split("/") if seg and not seg.startswith("{")]
    if not segments:
        return method.lower()
    return _to_camel_case(method.lower() + "_" + "_".join(segments))


def _to_camel_case(value: str) -> str:
    if not value:
        return "operation"
    # Split on snake_case underscores, hyphens, and camelCase boundaries.
    parts: list[str] = []
    buffer = ""
    for index, char in enumerate(value):
        if char in {"_", "-"}:
            if buffer:
                parts.append(buffer)
                buffer = ""
            continue
        if char.isupper() and buffer and not buffer[-1].isupper() and index > 0:
            parts.append(buffer)
            buffer = char.lower()
            continue
        buffer += char.lower()
    if buffer:
        parts.append(buffer)
    parts = [p for p in parts if p]
    if not parts:
        return "operation"
    return parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])


def _path_params(path: str, parameters: Iterable[Mapping[str, Any]]) -> list[str]:
    declared = {param.get("name") for param in parameters if param.get("in") == "path"}
    in_path = [segment.strip("{}") for segment in path.split("/") if segment.startswith("{") and segment.endswith("}")]
    names = [name for name in in_path if name in declared or name]
    return sorted(set(names))


def _header_params(parameters: Iterable[Mapping[str, Any]]) -> list[dict[str, Any]]:
    """Extract header parameters, preserving their original order."""
    result: list[dict[str, Any]] = []
    seen: set[str] = set()
    for param in parameters:
        if param.get("in") != "header":
            continue
        name = param.get("name", "")
        if not name or name in seen:
            continue
        seen.add(name)
        result.append({
            "name": name,
            "required": bool(param.get("required", False)),
            "ts_name": _to_camel_case(name.replace("-", "_")),
        })
    return result


def _render_operation(op: Mapping[str, Any]) -> str:
    name = op["function_name"]
    method = op["method"]
    path_template = op["path"]
    path_params = op["path_params"]
    has_body = op["has_body"]
    stream = op["stream"]
    if stream:
        return _render_stream_operation(op)
    signature_params: list[str] = [f"{param}: string" for param in path_params]
    if has_body:
        signature_params.append("body: unknown")
    signature = ", ".join(signature_params)
    if not path_params and not has_body:
        url_expr = f'"{path_template}"'
    else:
        replacements = {param: "${" + param + "}" for param in path_params}
        path_expr = path_template
        for param, expr in replacements.items():
            path_expr = path_expr.replace("{" + param + "}", expr)
        url_expr = "`" + path_expr + "`"
    if has_body:
        body_line = '    const response = await this.request<unknown>("{m}", {u}, body);'.format(m=method, u=url_expr)
    else:
        body_line = '    const response = await this.request<unknown>("{m}", {u}, undefined);'.format(m=method, u=url_expr)
    body_lines = [body_line, "    return response as never;"]
    summary = op["summary"]
    doc_lines = ["  /**"]
    if summary:
        doc_lines.append(f"   * {summary}")
    doc_lines.append(f"   * HTTP method {method}.")
    doc_lines.append("   */")
    signature_line = f"  async {name}({signature}): Promise<unknown> {{"
    return "\n".join(doc_lines + [signature_line] + body_lines + ["  }"])


def _render_stream_operation(op: Mapping[str, Any]) -> str:
    name = op["function_name"]
    method = op["method"]
    path_template = op["path"]
    path_params = op["path_params"]
    header_params = op.get("header_params", [])
    # Build signature: path params first, then optional header params
    signature_params = [f"{param}: string" for param in path_params]
    for hp in header_params:
        if hp["required"]:
            signature_params.append(f'{hp["ts_name"]}: string')
        else:
            signature_params.append(f'{hp["ts_name"]}?: string')
    signature = ", ".join(signature_params)
    if path_params:
        replacements = {param: "${" + param + "}" for param in path_params}
        path_expr = path_template
        for param, expr in replacements.items():
            path_expr = path_expr.replace("{" + param + "}", expr)
        url_expr = "`" + path_expr + "`"
    else:
        url_expr = f'"{path_template}"'
    summary = op["summary"]
    doc_lines = ["  /**"]
    if summary:
        doc_lines.append(f"   * {summary}")
    doc_lines.append("   * Returns an async iterable of sanitized SSE frame objects.")
    doc_lines.append("   */")
    # Build headers object, including optional header params
    header_lines = ['      headers: { "accept": "text/event-stream", ...this.defaultHeaders,']
    for hp in header_params:
        header_lines.append(f'        {("..." if not hp["required"] else "")}' +
                           f'({hp["ts_name"]} ? {{ "{hp["name"]}": String({hp["ts_name"]}) }} : {{}}),')
    header_lines.append("      },")
    body_lines = [
        f"  async *{name}({signature}): AsyncIterable<SseFrame> {{",
        f"    const response = await this.fetchImpl(this.baseUrl + {url_expr}, {{",
        f'      method: "{method}",',
    ]
    body_lines.extend(header_lines)
    body_lines.extend([
        "    });",
        "    if (!response.body) {",
        '      throw new PlatformApiError("stream body missing", { status: response.status, code: "stream_missing" });',
        "    }",
        "    const reader = response.body.getReader();",
        '    const decoder = new TextDecoder("utf-8");',
        '    let buffer = "";',
        "    while (true) {",
        "      const { value, done } = await reader.read();",
        "      if (done) break;",
        "      buffer += decoder.decode(value, { stream: true });",
        '      let boundary = buffer.indexOf("\\n\\n");',
        "      while (boundary !== -1) {",
        "        const rawFrame = buffer.slice(0, boundary);",
        "        buffer = buffer.slice(boundary + 2);",
        "        const frame = parseSseFrame(rawFrame);",
        "        if (frame) yield frame;",
        '        boundary = buffer.indexOf("\\n\\n");',
        "      }",
        "    }",
        "  }",
    ])
    return "\n".join(doc_lines + body_lines)


def _parse_args(argv: list[str]) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Generate the platform TypeScript SDK from OpenAPI.")
    parser.add_argument("--openapi", required=True, help="Path to the OpenAPI JSON file.")
    parser.add_argument("--out", required=True, help="Output TypeScript file path.")
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    args = _parse_args(list(sys.argv[1:] if argv is None else argv))
    with open(args.openapi, "r", encoding="utf-8") as fp:
        document = json.load(fp)
    text = generate_typescript(document)
    write_typescript(text, args.out)
    print(f"wrote {args.out} ({len(text)} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
