"""Tests for the platform-sdk-ts generator and the generated SDK.

The tests are stdlib-only Python. The TypeScript file is inspected as text
so the suite does not require a TypeScript toolchain.
"""

from __future__ import annotations

import json
import os
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[3]
OPENAPI_PATH = REPO_ROOT / "apps" / "platform_api" / "openapi" / "platform-api.json"
SDK_GENERATOR = REPO_ROOT / "packages" / "platform-sdk-ts" / "scripts" / "generate_sdk.py"
SDK_OUTPUT = REPO_ROOT / "packages" / "platform-sdk-ts" / "src" / "index.ts"


class SdkGeneratorCliTests(unittest.TestCase):
    def test_generator_runs_and_writes_file(self) -> None:
        with tempfile.TemporaryDirectory() as tmp_dir:
            out = Path(tmp_dir) / "sdk.ts"
            env = os.environ.copy()
            env["PYTHONPATH"] = os.pathsep.join([
                str(REPO_ROOT / "apps" / "platform_api" / "src"),
                str(REPO_ROOT / "packages" / "platform-contract" / "src"),
            ])
            result = subprocess.run(
                [
                    sys.executable,
                    str(SDK_GENERATOR),
                    "--openapi", str(OPENAPI_PATH),
                    "--out", str(out),
                ],
                env=env,
                check=True,
                capture_output=True,
                text=True,
            )
            self.assertEqual(result.returncode, 0)
            self.assertTrue(out.exists())
            text = out.read_text(encoding="utf-8")
            self.assertGreater(len(text), 100)
            self.assertIn("class PlatformApiClient", text)

    def test_generator_is_deterministic(self) -> None:
        with tempfile.TemporaryDirectory() as tmp_dir:
            out1 = Path(tmp_dir) / "sdk1.ts"
            out2 = Path(tmp_dir) / "sdk2.ts"
            env = os.environ.copy()
            env["PYTHONPATH"] = os.pathsep.join([
                str(REPO_ROOT / "apps" / "platform_api" / "src"),
                str(REPO_ROOT / "packages" / "platform-contract" / "src"),
            ])
            for out in (out1, out2):
                subprocess.run(
                    [
                        sys.executable,
                        str(SDK_GENERATOR),
                        "--openapi", str(OPENAPI_PATH),
                        "--out", str(out),
                    ],
                    env=env,
                    check=True,
                    capture_output=True,
                )
            self.assertEqual(out1.read_bytes(), out2.read_bytes())

    def test_generator_rejects_missing_arguments(self) -> None:
        result = subprocess.run(
            [sys.executable, str(SDK_GENERATOR)],
            capture_output=True,
            text=True,
        )
        self.assertNotEqual(result.returncode, 0)
        self.assertIn("usage", (result.stderr + result.stdout).lower())


class GeneratedSdkContentTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls) -> None:
        cls.text = SDK_OUTPUT.read_text(encoding="utf-8")

    def test_header_announces_generation(self) -> None:
        self.assertIn("Auto-generated by packages/platform-sdk-ts/scripts/generate_sdk.py", self.text)
        self.assertIn("Do not edit by hand.", self.text)
        self.assertIn("remote/thin", self.text)

    def test_exposes_all_operations(self) -> None:
        for name in ("createRun", "pollRun", "cancelRun", "submitApproval", "streamRun"):
            with self.subTest(name=name):
                self.assertIn(name, self.text)

    def test_sse_helper_present(self) -> None:
        self.assertIn("function parseSseFrame", self.text)
        self.assertIn("AsyncIterable<SseFrame>", self.text)

    def test_does_not_embed_local_runtime(self) -> None:
        for forbidden in (
            "DefaultRunRuntime",
            "BackendAdapter",
            "ChannelAdapter",
            "RunRequest",
            "import",  # not a Node import: keep SDK self-contained
        ):
            with self.subTest(token=forbidden):
                self.assertNotIn(forbidden, self.text)

    def test_sse_helper_parser_is_well_formed(self) -> None:
        # The SDK ships its own minimal SSE parser; assert it has the basic
        # line-split and event/id/data handling primitives.
        self.assertIn('lines = rawFrame.split("\\n")', self.text)
        self.assertIn('"event: "', self.text)
        self.assertIn('"id: "', self.text)
        self.assertIn('"data: "', self.text)


class OpenApiSourceOfTruthTests(unittest.TestCase):
    def test_openapi_contains_run_paths(self) -> None:
        document = json.loads(OPENAPI_PATH.read_text(encoding="utf-8"))
        paths = set(document["paths"].keys())
        for required in (
            "/v1/runs",
            "/v1/runs/{run_id}",
            "/v1/runs/{run_id}/approvals",
            "/v1/runs/{run_id}/events",
        ):
            with self.subTest(path=required):
                self.assertIn(required, paths)


if __name__ == "__main__":
    unittest.main()
